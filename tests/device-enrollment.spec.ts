import { test, expect } from "@playwright/test";
import { randomUUID } from "node:crypto";
import { writeFile } from "node:fs/promises";

// Keys stay in process memory; do not include this workflow in browser traces.
test.use({ trace: "off" });
test("register, approve, issue one-time key, rotate and revoke through the dashboard", async ({ page, request }) => {
  test.setTimeout(90000);
  test.skip(!process.env.DEVICE_TEST_PASSWORD || process.env.DEVICE_ENROLLMENT_TEST !== "true", "Requires explicit enrollment-test opt-in and local admin login");
  const identifier = `BROWSER-TEST-${randomUUID()}`;
  const api = process.env.API_URL ?? "http://localhost:5080";
  await page.goto("/login");
  await page.getByLabel("Username", { exact: true }).fill(process.env.DEVICE_TEST_USERNAME ?? "demo.admin");
  await page.getByLabel("Password", { exact: true }).fill(process.env.DEVICE_TEST_PASSWORD!);
  await page.getByRole("button", { name: "Sign in securely" }).click();
  await expect(page.getByRole("heading", { name: "Your field. In focus." })).toBeVisible();
  await page.getByRole("link", { name: "Devices & connections" }).click();
  await page.getByRole("button", { name: "Add device", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("Trimble device ID", { exact: true }).fill(identifier);
  await dialog.getByLabel("Device name / model", { exact: true }).fill("Browser test Android tablet");
  const response = page.waitForResponse(r => r.url() === `${api}/api/v1/devices/registrations` && r.request().method() === "POST");
  await dialog.getByRole("button", { name: "Register device", exact: true }).click();
  const createdResponse = await response;
  expect(createdResponse.status()).toBe(201);
  const created = await createdResponse.json();
  // Only identifiers are persisted for cleanup of this exact test-created row.
  await writeFile("../../.local/enrollment-browser-fixture.json", JSON.stringify({ ...created, identifier }));
  await expect(dialog).toHaveCount(0);
  const card = page.locator(".device-card").filter({ hasText: identifier });
  await expect(card).toBeVisible();
  await expect(card).toContainText("API Pending");
  await page.getByRole("button", { name: "Approve device", exact: true }).click();
  await dialog.getByRole("button", { name: "Approve device", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(card).toContainText("API Approved");
  await page.getByRole("button", { name: "Generate key", exact: true }).click();
  await dialog.getByRole("button", { name: "Generate key", exact: true }).click();
  const keyInput = dialog.getByLabel("Device key", { exact: true });
  await expect(keyInput).toBeVisible();
  const key = await keyInput.inputValue();
  expect(key.length).toBeGreaterThanOrEqual(64);
  expect((await request.post(`${api}/api/v1/devices/heartbeat`, { headers: { "X-Device-Key": key }, data: { pendingEventCount: 0 } })).status()).toBe(200);
  await dialog.getByRole("button", { name: "I have saved the key" }).click();
  await expect(page.locator("body")).not.toContainText(key);
  await page.getByRole("button", { name: "Replace key", exact: true }).click();
  await dialog.getByRole("button", { name: "Generate key", exact: true }).click();
  await expect(keyInput).toBeVisible();
  const replacement = await keyInput.inputValue();
  expect(replacement === key).toBe(false);
  expect((await request.post(`${api}/api/v1/devices/heartbeat`, { headers: { "X-Device-Key": key }, data: {} })).status()).toBe(401);
  await dialog.getByRole("button", { name: "I have saved the key" }).click();
  await page.getByRole("button", { name: "Revoke device", exact: true }).click();
  await dialog.getByRole("button", { name: "Revoke device", exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(card).toContainText("API Revoked");
  expect((await request.post(`${api}/api/v1/devices/heartbeat`, { headers: { "X-Device-Key": replacement }, data: {} })).status()).toBe(401);
  await expect(page.getByRole("button", { name: "Generate key", exact: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Replace key", exact: true })).toHaveCount(0);
  await page.screenshot({ path: "../../.local/device-enrollment-verified.png", fullPage: true });
});
