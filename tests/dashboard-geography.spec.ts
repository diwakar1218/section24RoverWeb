import { test, expect } from "@playwright/test";

const geography={states:[],districts:[],tehsils:[],villages:[]};
const empty={users:1,activeUsers:1,surveyors:1,rovers:0,online:0,offline:0,stale:0,connectedControllers:0,activeJobs:0,completedSurveys:0,points:0,areaM2:0,activeSessions:0,pendingSyncEvents:0,activeDistricts:0,workingSurveyors:0};
test("old hosted API shows saved totals, clickable point records and full Bhulekh filters without inventing live status",async({page})=>{
  const now=new Date().toISOString();let integrated=false,capabilities=false;
  const session={id:"saved-survey",project:"Park survey",userId:"owner",deviceId:"installation",surveyorName:"Surveyor One",district:"Agra",tehsil:"Tehsil A",village:"Village A",districtCode:"146",tehsilCode:"00766",villageCode:"124639",gataNo:"12/3",caseNo:"CASE-77",totalArea:77.42,totalPoints:4,totalDistance:36,status:"completed",mode:"polygon",startedAt:now,provenance:"mobile"};
  const points=[0,1,2,3].map(i=>({id:"p"+i,pointNumber:"P"+(i+1),name:"Corner",latitude:25.31+i/100000,longitude:82.97,capturedAt:now,address:"Saved park address"}));
  await page.route("**/api/v1/**",async route=>{
    const url=new URL(route.request().url()),path=url.pathname;let data:unknown=[];
    if(path.endsWith("/auth/refresh"))data={accessToken:"fixture"};
    else if(path.endsWith("/auth/me"))data={userId:"admin",organizationId:"org",name:"Administrator",grants:["dashboard.read","rovers.read","surveys.read"].map(permission=>({permission,scope:"Organization"}))};
    else if(path.endsWith("/capabilities"))return route.fulfill({status:capabilities?200:404,json:capabilities?{integratedDashboard:true}: {title:"Old API"}});
    else if(path.endsWith("/rover-hours"))return route.fulfill({status:404,json:{title:"Old API"}});
    else if(path.endsWith("/mobile/monitoring/devices"))return route.fulfill({status:integrated?403:404,json:{title:integrated?"Not permitted":"Old API"}});
    else if(path.endsWith("/summary"))data=integrated?{...empty,rovers:1,points:4,areaM2:77.42,completedSurveys:1}:empty;
    else if(path.endsWith("/rovers"))data={items:[],total:0};
    else if(path.endsWith("/surveys"))data={items:[],total:0};
    else if(path.endsWith("/geography"))data=geography;
    else if(path.endsWith("/survey/history"))data=[session];
    else if(path.endsWith("/survey/saved-survey"))data={session,points,track:[]};
    else if(path.endsWith("/land-records/district"))data=[{code:"999",name:"Zila Z"},{code:"146",name:"Agra"}];
    else if(path.endsWith("/land-records/tehsil"))data=[{code:"00766",name:"Tehsil A"}];
    else if(path.endsWith("/land-records/village"))data=[{code:"124639",name:"Village A"}];
    await route.fulfill({json:data});
  });
  await page.route("**/hubs/monitoring**",route=>route.fulfill({status:503}));
  await page.goto("/dashboard");
  await expect(page.locator(".kpi-points .kpi-value")).toHaveText("4");
  await expect(page.locator(".kpi-rovers .kpi-value")).toHaveText("1");
  await expect(page.locator(".kpi-online .kpi-value")).toContainText("Unavailable");
  await expect(page.locator(".rover-rows").first()).toContainText("Unknown");
  await page.getByRole("button",{name:"Show details: Survey points",exact:true}).click();
  const records=page.getByRole("region",{name:"Survey points detailed records"});
  await expect(records.locator("tbody tr")).toHaveCount(4);
  await expect(records).toContainText("CASE-77");await expect(records).toContainText("Saved park address");
  await page.getByRole("button",{name:"Show details: Surveyed area",exact:true}).click();
  await expect(page.getByRole("region",{name:"Surveyed area detailed records"}).locator("tbody tr")).toHaveCount(1);
  await page.getByRole("button",{name:"Show details: Rover connections",exact:true}).click();
  await expect(page.getByRole("region",{name:"Rover connections detailed records"}).locator("tbody tr")).toHaveCount(1);
  await page.goto("/dashboard/mobile-surveys");
  const filters=page.getByRole("region",{name:"Survey filters"});
  await filters.getByRole("button",{name:"District",exact:true}).click();
  await expect(page.getByRole("listbox").getByRole("option")).toHaveText(["All districts","Agra","Zila Z"]);
  await page.getByRole("option",{name:"Zila Z",exact:true}).click();
  await filters.getByRole("button",{name:"Tehsil",exact:true}).click();
  await page.getByRole("option",{name:"Tehsil A",exact:true}).click();
  await filters.getByRole("button",{name:"Village",exact:true}).click();
  await page.getByRole("option",{name:"Village A",exact:true}).click();
  await expect(page.getByText("No surveys match these filters.",{exact:true})).toBeVisible();
  integrated=true;await page.goto("/login");await page.reload();await page.goto("/dashboard");
  await expect(page.locator(".kpi-points .kpi-value")).toHaveText("4");
  await expect(page.locator(".kpi-areaM2 .kpi-value")).toContainText("77.42");
  capabilities=true;await page.reload();
  await expect(page.locator(".kpi-points .kpi-value")).toHaveText("4");
});

test("user and job forms remove State and resolve searched Bhulekh selection into UUIDs before saving",async({page})=>{
  const selected={stateId:"30000000-0000-0000-0000-000000000001",districtId:"31000000-0000-0000-0000-000000000001",tehsilId:"32000000-0000-0000-0000-000000000001",villageId:"33000000-0000-0000-0000-000000000001"};
  let resolved:unknown,saved:Record<string,unknown>|undefined;
  await page.route("**/api/v1/**",async route=>{
    const path=new URL(route.request().url()).pathname;let data:unknown=[];
    if(path.endsWith("/auth/refresh"))data={accessToken:"fixture"};
    else if(path.endsWith("/auth/me"))data={userId:"admin",organizationId:"org",name:"Administrator",grants:["users.manage","roles.manage","users.read","surveys.read","surveys.manage"].map(permission=>({permission,scope:"Organization"}))};
    else if(path.endsWith("/geography/resolve")){resolved=route.request().postDataJSON();data=selected;}
    else if(path.endsWith("/geography"))data=saved?{states:[{id:selected.stateId,name:"Uttar Pradesh",parentId:null}],districts:[{id:selected.districtId,name:"Agra Hindi",parentId:selected.stateId}],tehsils:[{id:selected.tehsilId,name:"Tehsil A",parentId:selected.districtId}],villages:[{id:selected.villageId,name:"Village A",parentId:selected.tehsilId}]}:geography;
    else if(path.endsWith("/roles"))data=[{id:"role-surveyor",name:"Surveyor",scope:"Own"}];
    else if(path.endsWith("/land-records/district"))data=[{code:"999",name:"Zila Z"},{code:"146",name:"Agra Hindi",englishName:"Agra"}];
    else if(path.endsWith("/land-records/tehsil"))data=[{code:"00766",name:"Tehsil A"}];
    else if(path.endsWith("/land-records/village"))data=[{code:"124639",name:"Village A"},{code:"124640",name:"Village B"}];
    else if(path.endsWith("/users")&&route.request().method()==="POST"){saved=route.request().postDataJSON();data={id:"created-user"};}
    else if(path.endsWith("/users/created-user/management"))data={profile:{id:"created-user",fullName:"New surveyor",username:"new.surveyor",roles:["Surveyor"],isActive:true,...selected},roleIds:["role-surveyor"],version:0};
    await route.fulfill({json:data});
  });
  await page.goto("/dashboard/users/create");
  await expect(page.getByRole("heading",{name:"Create user."})).toBeVisible();
  await expect(page.getByLabel("State",{exact:true})).toHaveCount(0);
  await page.getByLabel("Full name",{exact:true}).fill("New surveyor");
  await page.getByLabel("Username",{exact:true}).fill("new.surveyor");
  await page.getByLabel("Initial password",{exact:false}).fill("Eight!12");
  await page.getByRole("checkbox",{name:/Surveyor/}).check();
  await page.getByRole("button",{name:"District",exact:true}).click();
  await page.getByRole("textbox",{name:"Search District",exact:true}).fill("Agra");
  await page.getByRole("option",{name:/Agra Hindi/}).click();
  await page.getByRole("button",{name:"Tehsil",exact:true}).click();
  await page.getByRole("option",{name:"Tehsil A",exact:true}).click();
  await page.getByRole("button",{name:"Village",exact:true}).click();
  await page.getByRole("option",{name:"Village A",exact:true}).click();
  await page.getByRole("button",{name:"Save user",exact:true}).click();
  await expect.poll(()=>saved).toBeDefined();
  expect(resolved).toEqual({districtCode:"146",tehsilCode:"00766",villageCode:"124639"});
  expect(saved).toMatchObject({...selected,initialPassword:"Eight!12"});expect(saved).not.toHaveProperty("landRecord");
  await page.goto("/dashboard/users/created-user/edit");
  await expect(page.getByRole("heading",{name:"Edit user."})).toBeVisible();
  await page.getByRole("button",{name:"Village",exact:true}).click();
  await expect(page.getByRole("option",{name:"Village B",exact:true})).toBeVisible();
  await page.goto("/dashboard/surveys/create");
  await expect(page.getByRole("heading",{name:"Create survey job."})).toBeVisible();
  await expect(page.getByLabel("State",{exact:true})).toHaveCount(0);
  await page.getByRole("button",{name:"District",exact:true}).click();
  await expect(page.getByRole("option",{name:/Agra Hindi/})).toBeVisible();
  await expect(page.getByRole("option",{name:"Zila Z",exact:true})).toBeVisible();
});
